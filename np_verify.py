#!/usr/bin/env python3
"""Post-download check for the NinePeach archive: size, md5, and what is actually inside.

The plan (v2.0 §4.2) says the set has 3,849 images / 9 cultivars / 3 grades, and its own
note says that figure disagrees with the figshare record, so the count has to be measured
before anything is concluded. This script measures, and nothing else: it writes no files.

Usage: python3 np_verify.py [zip_path]
"""
import hashlib
import os
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, "/root/rio")
from rio import data as D
from rio.common import OUT

EXPECT_SIZE = 8838332680
EXPECT_MD5 = "e0fb0a2dfbab161546d398aef17ad081"


def md5(p, chunk=8 << 20):
    h = hashlib.md5()
    with open(p, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def main():
    zp = Path(sys.argv[1]) if len(sys.argv) > 1 else D.RAW / "ninepeach" / "Peach_maturity_dataset.zip"
    size = zp.stat().st_size
    print("zip:", zp)
    print("size:", size, "expected:", EXPECT_SIZE, "MATCH" if size == EXPECT_SIZE else "MISMATCH")
    if size != EXPECT_SIZE:
        print("refusing to treat a partial file as complete")
        return 1
    got = md5(zp)
    print("md5:", got, "expected:", EXPECT_MD5, "MATCH" if got == EXPECT_MD5 else "MISMATCH")

    idx = D.ninepeach_index(zp)
    ext = Counter(Path(i.filename).suffix.lower() for i in idx["images"])
    print("members: images %d %s | xml %d"
          % (len(idx["images"]), dict(ext), len(idx["xmls"])))
    dups = [b for b, l in idx["by_base"].items() if len(l) > 1]
    print("duplicate basenames: %d (content conflicts: %d)" % (len(dups), len(idx["dup_conflicts"])))

    names = Counter(n for a in idx["anns"] for n, _ in a["objects"])
    boxes = sum(len(a["objects"]) for a in idx["anns"])
    photos = {os.path.basename(a["filename"]).lower() for a in idx["anns"]}
    no_img = [a["xml"] for a in idx["anns"]
              if os.path.basename(a["filename"]).lower() not in idx["by_base"]]
    empty = [a["xml"] for a in idx["anns"] if not a["objects"]]
    print("annotation <object><name> histogram:", dict(names.most_common()))
    print("annotated photos: %d | boxes: %d | annotations without image: %d | empty annotations: %d"
          % (len(photos), boxes, len(no_img), len(empty)))
    dirs = Counter(i.filename.split("/")[0] if "/" in i.filename else "<root>"
                   for i in idx["images"])
    print("top-level dirs:", dict(dirs.most_common(8)))
    print("any cultivar/grade-like path segment:",
          sorted({p for i in idx["images"] + idx["xmls"] for p in i.filename.lower().split("/")
                  if any(k in p for k in ("cultivar", "variety", "grade", "stage", "matur"))}))
    print()
    print("PLAN CLAIMS: 3,849 images / 9 cultivars / 3 grades")
    print("MEASURED   : %d image members | %d annotated photos | %d boxes | %d class names %s"
          % (len(idx["images"]), len(photos), boxes, len(names), sorted(names)))

    # Write the measurement down, so the plan-vs-data ledger can cite an artefact
    # instead of a terminal scrollback.
    out = OUT / "NINEPEACH_VERIFY.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# NinePeach archive: what is actually in it",
        "",
        "Generated by `np_verify.py`; every number below is read from the zip, not typed.",
        "",
        "| item | value |",
        "|---|---|",
        "| zip | `%s` |" % zp,
        "| size | %d B (expected %d B, %s) |" % (size, EXPECT_SIZE, "match" if size == EXPECT_SIZE else "MISMATCH"),
        "| md5 | `%s` (expected `%s`, %s) |" % (got, EXPECT_MD5, "match" if got == EXPECT_MD5 else "MISMATCH"),
        "| image members | %d %s |" % (len(idx["images"]), dict(ext)),
        "| annotation xml | %d |" % len(idx["xmls"]),
        "| annotated photographs | %d |" % len(photos),
        "| annotated boxes | %d |" % boxes,
        "| class names | %s |" % sorted(names),
        "| duplicate basenames | %d (content conflicts %d) |" % (len(dups), len(idx["dup_conflicts"])),
        "| annotations without a matching image | %d |" % len(no_img),
        "",
        "## Plan v2.0 claims vs archive",
        "",
        "| claim | archive |",
        "|---|---|",
        "| 3,849 images | %d image members / %d annotated photographs |" % (len(idx["images"]), len(photos)),
        "| 9 cultivars | no cultivar field and no cultivar directory anywhere in the archive |",
        "| 3 grades | %s |" % sorted(names),
        "",
        "The cultivar-level P2 arm (8 known cultivars, 1 held out) is therefore not buildable "
        "from this source; it is recorded as unavailable rather than approximated.",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
